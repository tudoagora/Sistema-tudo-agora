-- `with schema public` e explicito de proposito: 20260101000002_search.sql
-- chama public.unaccent() e usa similarity() dentro de funcoes com
-- search_path = public. Sem fixar o schema, o Postgres escolheria o primeiro
-- schema do search_path do executor -- no Supabase hospedado as extensoes
-- pre-existentes vivem em `extensions`, e o resultado dependeria de quem rodou.
create extension if not exists pg_trgm with schema public;
create extension if not exists unaccent with schema public;

-- ---------- ENUMS ----------

create type business_status as enum ('draft', 'pending', 'active', 'suspended');
create type fulfillment_mode as enum ('delivery', 'pickup');
create type order_fulfillment as enum ('delivery', 'pickup');
create type order_status as enum (
  'pending', 'confirmed', 'preparing', 'out_for_delivery',
  'ready_for_pickup', 'completed', 'cancelled'
);
create type payment_method as enum ('pix', 'cash', 'card_on_delivery', 'card_online');
create type payment_status as enum ('pending', 'paid', 'failed', 'refunded');
create type plan_period as enum ('month', 'year');
create type subscription_status as enum ('pending', 'active', 'past_due', 'cancelled', 'expired');
create type profile_role as enum ('customer', 'merchant', 'admin');
create type member_role as enum ('owner', 'manager');
create type quote_status as enum ('new', 'contacted', 'won', 'lost');

-- ---------- GEOGRAFIA ----------

create table public.cities (
  id         bigint generated by default as identity primary key,
  name       text not null,
  state      text not null,
  slug       text not null unique,
  timezone   text not null default 'America/Cuiaba',
  is_active  boolean not null default true,
  created_at timestamptz not null default now()
);

-- Grupos da home (as 9 pílulas/imagens da seção CATEGORIAS)
create table public.groups (
  id         bigint generated by default as identity primary key,
  name       text not null,
  slug       text not null unique,
  image_url  text,
  sort_order integer not null default 0,
  is_active  boolean not null default true
);

-- Categorias de negócio (subdivide os grupos)
create table public.categories (
  id              bigint generated by default as identity primary key,
  name            text not null,
  slug            text not null unique,
  group_id        bigint references public.groups(id) on delete set null,
  -- categoria que aceita cardápio/pedido online
  is_order_capable boolean not null default false,
  sort_order      integer not null default 0,
  is_active       boolean not null default true
);

create index categories_group_idx on public.categories (group_id);

-- ---------- EMPRESAS ----------
-- unifica os 26 `empresa` (WP) + 17 serviços + 10 lojas (subdomínios)

create table public.businesses (
  id              bigint generated by default as identity primary key,
  city_id         bigint not null references public.cities(id) on delete restrict,
  name            text not null,
  slug            text not null,
  -- subdomínio próprio: masterfarma, metal, ricardocelular...
  custom_slug     text unique,

  description     text,
  logo_url        text,
  cover_url       text,

  phone           text,
  whatsapp        text,
  email           text,
  instagram       text,
  address         text,
  neighborhood    text,
  latitude        numeric(10, 7),
  longitude       numeric(10, 7),
  -- {"mon":[["08:00","12:00"]], ...} ou {"special":"24/7"}
  opening_hours   jsonb not null default '{}'::jsonb,

  fulfillment     fulfillment_mode[] not null default '{}',
  payment_methods text[] not null default '{}',
  pix_key         text,
  delivery_fee_cents bigint not null default 0 check (delivery_fee_cents >= 0),
  min_order_cents    bigint not null default 0 check (min_order_cents >= 0),

  -- Plano Executivo: solicita orçamento
  accepts_quote   boolean not null default false,

  status          business_status not null default 'draft',
  is_featured     boolean not null default false,
  featured_until  timestamptz,

  -- proveniência da migração
  source          text,
  legacy_wp_id    bigint,

  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),

  unique (city_id, slug),
  constraint businesses_custom_slug_format check (
    custom_slug is null or custom_slug ~ '^[a-z0-9]([a-z0-9-]*[a-z0-9])?$'
  )
);

create index businesses_city_status_idx on public.businesses (city_id, status);
create index businesses_name_trgm_idx  on public.businesses using gin (name gin_trgm_ops);
create index businesses_custom_slug_idx on public.businesses (custom_slug);
create index businesses_featured_idx   on public.businesses (is_featured, featured_until);

-- N:N — substitui o `data-ta-groups` multi-label do HTML
