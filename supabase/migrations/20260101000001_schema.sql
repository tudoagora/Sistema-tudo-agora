-- ---------- PEDIDOS ----------

create table public.orders (
  id                bigint generated by default as identity primary key,
  -- código curto exibido ao cliente e ao lojista (ex.: TA-4F2K9)
  public_id         text not null unique,

  business_id       bigint not null references public.businesses(id) on delete restrict,
  customer_id       uuid references auth.users(id) on delete set null,
  customer_name     text not null,
  customer_phone    text not null,
  customer_email    text,

  fulfillment       order_fulfillment not null,
  address           text,
  address_notes     text,

  status            order_status not null default 'pending',
  payment_method    payment_method not null,
  payment_status    payment_status not null default 'pending',
  payment_provider  text,
  payment_reference text,

  subtotal_cents    bigint not null default 0 check (subtotal_cents >= 0),
  delivery_fee_cents bigint not null default 0 check (delivery_fee_cents >= 0),
  discount_cents    bigint not null default 0 check (discount_cents >= 0),
  total_cents       bigint not null default 0 check (total_cents >= 0),

  notes             text,
  cancellation_reason text,

  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  confirmed_at      timestamptz,
  completed_at      timestamptz,

  constraint orders_delivery_needs_address check (
    fulfillment <> 'delivery' or address is not null
  )
);

create index orders_business_status_idx on public.orders (business_id, status, created_at desc);
create index orders_customer_idx        on public.orders (customer_id, created_at desc);
create index orders_public_id_idx       on public.orders (public_id);

